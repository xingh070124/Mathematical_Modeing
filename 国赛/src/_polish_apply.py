REPLACEMENTS = TYPO + QUOTE + DASH + PROSE


def main() -> int:
    src = open(TEX, encoding="utf-8", newline="").read()
    crlf = src.count("\r\n")
    print(f"原文件 {len(src)} 字符, CRLF 行 {crlf} 处")
    problems = []
    for i, (old, new) in enumerate(REPLACEMENTS):
        n = src.count(old)
        if n != 1:
            problems.append((i, n, old[:40]))
    if problems:
        print("\n!! 以下条目匹配数不为 1, 整批中止:")
        for i, n, s in problems:
            print(f"   #{i}  匹配 {n} 次  {s!r}")
        return 1
    print(f"全部 {len(REPLACEMENTS)} 条均唯一匹配, 开始应用。")

    out = src
    for old, new in REPLACEMENTS:
        out = out.replace(old, new, 1)

    if DRY:
        print("--dry-run: 未写文件")
        return 0

    bak = TEX + time.strftime(".bak_polish_%Y%m%d_%H%M%S")
    open(bak, "w", encoding="utf-8", newline="").write(src)
    # 保持原来的行尾风格
    open(TEX, "w", encoding="utf-8", newline="").write(out)
    chk = open(TEX, encoding="utf-8", newline="").read()
    ok = all(new in chk for _old, new in REPLACEMENTS)
    print(f"备份 : {os.path.basename(bak)}")
    print(f"写回 : {len(src)} -> {len(chk)} 字符;  回读校验 {'OK' if ok else '!! 失败'}")
    print(f"剩余破折号 —— : {chk.count('——')}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
